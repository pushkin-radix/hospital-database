DOSAGES = ["1 tablet twice daily", "1 tablet once daily", "1 tablet at night",
           "1 tablet three times daily", "Apply twice daily", "As directed"]

N_PATIENTS = 600
N_APPOINTMENT_ATTEMPTS = 2400


def q(s):
    """SQL string literal."""
    return "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"


def phone():
    return "9" + "".join(random.choice("0123456789") for _ in range(9))


def money(x):
    return f"{x:.2f}"


def emit(table, cols, rows, batch=200):
    for i in range(0, len(rows), batch):
        chunk = rows[i:i + batch]
        print(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
        print(",\n".join("  (" + ", ".join(r) + ")" for r in chunk) + ";")
    print()


def main():
    print("-- Sample data for hospital_db (synthetic; generated by generate_sample_data.py)")
    print("USE hospital_db;\nSET FOREIGN_KEY_CHECKS = 0;\n")

    # departments
    emit("departments", ["name", "floor_no", "phone"],
         [[q(d[0]), str(d[1]), q("0431-25000" + str(i))] for i, d in enumerate(DEPTS)])

    # doctors: 3 per department; first 3 get demo database logins
    doctors = []  # (id, dept_idx, fee)
    rows = []
    did = 0
    for di, d in enumerate(DEPTS):
        for k in range(3):
            did += 1
            first = random.choice(FIRST_M + FIRST_F)
            last = random.choice(LAST)
            fee = d[3] + 100 * k
            doctors.append((did, di, fee))
            uname = f"dr_demo{did}" if did <= 3 else None
            rows.append([str(di + 1), q(first), q(last), q(d[2]),
                         q(f"{first.lower()}.{last.lower()}{did}@hospital.example"),
                         q(phone()), money(fee),
                         q(uname) if uname else "NULL",
                         q((date(2015, 1, 1) + timedelta(days=random.randint(0, 3000))).isoformat()),
                         "1"])
    emit("doctors", ["department_id", "first_name", "last_name", "specialization", "email",
                     "phone", "consultation_fee", "db_username", "joined_on", "is_active"], rows)

    # patients
    rows = []
    for pid in range(1, N_PATIENTS + 1):
        g = random.choice("FM") if random.random() < 0.98 else "O"
        first = random.choice(FIRST_F if g == "F" else FIRST_M)
        last = random.choice(LAST)
        age_days = random.randint(0, 85 * 365)
        dob = TODAY - timedelta(days=age_days + 30)
        reg = TODAY - timedelta(days=random.randint(30, 900))
        rows.append([q(first), q(last), q(dob.isoformat()), q(g),
                     q(random.choices(BLOOD, BLOOD_W)[0]) if random.random() < 0.85 else "NULL",
                     q(phone()), q(f"{first.lower()}.{last.lower()}{pid}@mail.example"),
                     q(random.choice(CITIES)), q(reg.isoformat())])
    emit("patients", ["first_name", "last_name", "date_of_birth", "gender", "blood_group",
                      "phone", "email", "city", "registered_on"], rows)

    # medicines
    emit("medicines", ["name", "unit_price", "stock_qty"],
         [[q(n), money(p), str(random.randint(200, 3000))] for n, p in MEDS])

    # appointments (unique doctor+slot)
    slots = [f"{h:02d}:{m:02d}:00" for h in range(9, 17) for m in (0, 30)]
    used = set()
    appts = []  # dict per appointment
    start = date(2025, 10, 1)
    for _ in range(N_APPOINTMENT_ATTEMPTS):
        doc = random.choice(doctors)
        if random.random() < 0.12:  # future bookings
            day = TODAY + timedelta(days=random.randint(1, 35))
        else:
            day = start + timedelta(days=random.randint(0, (TODAY - start).days - 1))
        if day.weekday() == 6:  # no Sundays
            continue
        slot = random.choice(slots)
        key = (doc[0], day, slot)
        if key in used:
            continue
        used.add(key)
        d = DEPTS[doc[1]]
        if day > TODAY:
            status = "SCHEDULED"
        else:
            status = random.choices(["COMPLETED", "CANCELLED", "NO_SHOW"], [82, 12, 6])[0]
        appts.append({
            "patient": random.randint(1, N_PATIENTS), "doctor": doc[0], "fee": doc[2],
            "at": f"{day.isoformat()} {slot}", "day": day, "status": status,
            "reason": random.choice(d[5]),
            "diagnosis": random.choice(d[4]) if status == "COMPLETED" else None,
            "notes": ("Advised rest, fluids and follow-up if symptoms persist."
                      if status == "COMPLETED" and random.random() < 0.5 else None),
        })
    appts.sort(key=lambda a: a["at"])
    emit("appointments",
         ["patient_id", "doctor_id", "appointment_at", "status", "reason", "diagnosis", "notes"],
         [[str(a["patient"]), str(a["doctor"]), q(a["at"]), q(a["status"]), q(a["reason"]),
           q(a["diagnosis"]) if a["diagnosis"] else "NULL",
           q(a["notes"]) if a["notes"] else "NULL"] for a in appts])

    # prescriptions, items, invoices, payments
    price = {i + 1: p for i, (_, p) in enumerate(MEDS)}
    presc_rows, item_rows, inv_rows, pay_rows = [], [], [], []
    pres_id = 0
    inv_id = 0
    for aid, a in enumerate(appts, start=1):
        if a["status"] != "COMPLETED":
            continue
        med_total = 0.0
        if random.random() < 0.70:
            pres_id += 1
            presc_rows.append([str(aid), q(a["day"].isoformat())])
            for mid in random.sample(range(1, len(MEDS) + 1), random.randint(1, 3)):
                qty = random.choice([5, 6, 10, 10, 14, 15, 20, 30])
                item_rows.append([str(pres_id), str(mid), str(qty), money(price[mid]), q(random.choice(DOSAGES))])
                med_total += qty * price[mid]
        inv_id += 1
        total = a["fee"] + med_total
        r = random.random()
        if r < 0.70:
            status = "PAID"
            splits = [total] if random.random() < 0.8 else [round(total * 0.5, 2), None]
        elif r < 0.82:
            status = "PARTIAL"
            splits = [round(total * random.choice([0.3, 0.5, 0.6]), 2)]
        else:
            status = "PENDING"
            splits = []
        inv_rows.append([str(aid), money(a["fee"]), money(med_total), q(status), q(a["day"].isoformat())])
        paid_so_far = 0.0
        for n, amt in enumerate(splits):
            amt = round(total - paid_so_far, 2) if amt is None else round(amt, 2)
            paid_so_far += amt
            when = datetime.fromisoformat(a["at"]) + timedelta(hours=1 + n * 72)
            pay_rows.append([str(inv_id), money(amt), q(random.choice(["CASH", "CARD", "UPI", "INSURANCE"])),
                             q(when.strftime("%Y-%m-%d %H:%M:%S"))])
    emit("prescriptions", ["appointment_id", "issued_on"], presc_rows)
    emit("prescription_items", ["prescription_id", "medicine_id", "quantity", "unit_price", "dosage"], item_rows)
    emit("invoices", ["appointment_id", "consultation_fee", "medicine_total", "status", "issued_on"], inv_rows)
    emit("payments", ["invoice_id", "amount", "method", "paid_at"], pay_rows)

    print("SET FOREIGN_KEY_CHECKS = 1;")


if __name__ == "__main__":
    main()
