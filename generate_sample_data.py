"""Generate sample_data.sql for the hospital database.

Everything here is synthetic. Names, phone numbers and emails are random
combinations and do not belong to real people. A fixed seed makes the output
reproducible:  python3 generate_sample_data.py > sample_data.sql
"""
import random
from datetime import date, datetime, timedelta

random.seed(2026)
TODAY = date(2026, 10, 9)

FIRST_F = ["Ananya", "Divya", "Kavya", "Meena", "Priya", "Lakshmi", "Nisha", "Swathi",
           "Deepa", "Revathi", "Harini", "Sneha", "Pooja", "Janani", "Keerthi", "Anitha"]
